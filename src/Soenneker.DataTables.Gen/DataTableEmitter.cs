using System;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using static Soenneker.DataTables.Gen.SymbolMetadata;

namespace Soenneker.DataTables.Gen;

internal static class DataTableEmitter
{
    private static readonly DiagnosticDescriptor _unsupportedModel = new("SDTG001", "Unsupported table model", "'{0}' must be a non-generic, non-file-local, top-level class, record, or struct", "DataTables", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor _duplicateColumn = new("SDTG002", "Ambiguous table column", "'{0}' has a duplicate column name or field path '{1}' (case-insensitive)", "DataTables", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor _unsupportedSearch = new("SDTG003", "Unsupported searchable property", "'{0}' has unsupported search type '{1}'; use a string, boolean, enum, or string EnumValue, or set GenerateSearchExpressions = false for metadata only", "DataTables", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor _companionCollision = new("SDTG004", "Companion name is already declared", "'{0}' is already declared; rename it to allow generating the table companion", "DataTables", DiagnosticSeverity.Error, true);

    internal static void Emit(SourceProductionContext context, INamedTypeSymbol model)
    {
        if (model.Arity != 0 || model.ContainingType != null || model.IsFileLocal || model.IsRefLikeType || model.IsStatic)
        {
            context.ReportDiagnostic(Diagnostic.Create(_unsupportedModel, model.Locations.FirstOrDefault(), model.Name));
            return;
        }
        string companion = model.Name + "DataTable";
        if (model.ContainingNamespace.GetTypeMembers(companion).Length != 0)
        {
            context.ReportDiagnostic(Diagnostic.Create(_companionCollision, model.Locations.FirstOrDefault(), companion));
            return;
        }
        AttributeData? options = Attribute(model, "Soenneker.DataTables.Gen.GenerateDataTableAttribute");
        bool expressions = options != null && Flag(options, "GenerateSearchExpressions", true);
        var columns = PropertyPaths(model, Flag(options, "IncludeNestedProperties"));
        var aliases = new System.Collections.Generic.Dictionary<string, IPropertySymbol[]>(StringComparer.OrdinalIgnoreCase);
        foreach (IPropertySymbol[] column in columns)
        {
            foreach (string alias in new[] { ExternalName(column), Field(column) }.Distinct(StringComparer.OrdinalIgnoreCase))
            {
                if (aliases.TryGetValue(alias, out IPropertySymbol[]? existing) && existing != column)
                {
                    context.ReportDiagnostic(Diagnostic.Create(_duplicateColumn, column.Last().Locations.FirstOrDefault(), model.Name, alias));
                    return;
                }
                aliases[alias] = column;
            }
            if (expressions && Column(column).Searchable && !SupportsSearch(column.Last().Type) && !StringLeaves(column, columns).Any())
            {
                context.ReportDiagnostic(Diagnostic.Create(_unsupportedSearch, column.Last().Locations.FirstOrDefault(), ExternalName(column), column.Last().Type.ToDisplayString()));
                return;
            }
        }
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        bool hasNamespace = !model.ContainingNamespace.IsGlobalNamespace;
        if (hasNamespace) code.Append("namespace ").Append(model.ContainingNamespace.ToDisplayString()).Append("\n{\n");
        code.Append("/// <summary>Compile-time column metadata and search operations for ").Append(model.Name).Append(".</summary>\n")
            .Append(model.DeclaredAccessibility == Accessibility.Public ? "public" : "internal").Append(" static class ").Append(companion).Append("\n{\n");
        ColumnDtoEmitter.Emit(code, columns);
        foreach (bool searchable in new[] { true, false })
        {
            string name = searchable ? "SearchableFields" : "OrderableFields";
            code.Append("    /// <summary>Explicitly permitted ").Append(searchable ? "search" : "order").Append(" field paths.</summary>\n")
                .Append("    public static global::System.Collections.Generic.IReadOnlyList<string> ").Append(name)
                .Append(" { get; } = global::System.Array.AsReadOnly(new string[] { ")
                .Append(string.Join(", ", columns.Where(c => searchable ? Column(c).Searchable : Column(c).Orderable).Select(c => Field(c)).Distinct(StringComparer.OrdinalIgnoreCase).Select(Quote)))
                .Append(" });\n");
        }
        if (Flag(options, "GenerateRequestMapping", true)) RequestDtoEmitter.Emit(code);
        if (expressions)
        {
            string type = TypeName(model);
            code.Append("    /// <summary>Builds a predicate for one searchable column or mapped field; returns null for an unknown or disallowed field.</summary>\n")
                .Append("    public static global::System.Linq.Expressions.Expression<global::System.Func<").Append(type).Append(", bool>>? GetFieldPredicate(string field, string term)\n    {\n")
                .Append("        if (field == null) throw new global::System.ArgumentNullException(nameof(field));\n        if (term == null) throw new global::System.ArgumentNullException(nameof(term));\n        switch (field.ToLowerInvariant())\n        {\n");
            foreach (IPropertySymbol[] column in columns.Where(c => Column(c).Searchable)) EmitPredicate(code, column, columns);
            code.Append("            default: return null;\n        }\n    }\n");
            EmitSearch(code, type);
        }
        code.Append("}\n");
        if (hasNamespace) code.Append("}\n");
        context.AddSource(model.ToDisplayString() + ".DataTable.g.cs", code.ToString());
    }

    private static bool SupportsSearch(ITypeSymbol type) => type.SpecialType == SpecialType.System_String || type.SpecialType == SpecialType.System_Boolean ||
        type.TypeKind == TypeKind.Enum || type is INamedTypeSymbol named && (IsEnumValue(named) ||
            named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T && named.TypeArguments[0].SpecialType == SpecialType.System_Boolean);

    private static System.Collections.Generic.IEnumerable<IPropertySymbol[]> StringLeaves(IPropertySymbol[] parent, System.Collections.Generic.List<IPropertySymbol[]> columns) =>
        columns.Where(path => path.Length > parent.Length && path.Take(parent.Length).SequenceEqual(parent, SymbolEqualityComparer.Default) && path.Last().Type.SpecialType == SpecialType.System_String);

    private static void EmitPredicate(StringBuilder code, IPropertySymbol[] column, System.Collections.Generic.List<IPropertySymbol[]> columns)
    {
        foreach (string alias in new[] { ExternalName(column), Field(column) }.Distinct(StringComparer.OrdinalIgnoreCase))
            code.Append("            case ").Append(Quote(alias.ToLowerInvariant())).Append(":\n");
        code.Append("            {\n");
        AttributeData? options = Attribute(column.Last(), "Soenneker.DataTables.Gen.DataTableSearchOptionsAttribute");
        bool ignoreCase = Flag(options, "IgnoreCase", true);
        string removed = Text(options, "RemoveCharacters") ?? "";
        code.Append("                string value = ").Append(Normalize("term", ignoreCase, removed, true)).Append(";\n")
            .Append("                if (value.Length == 0) return item => false;\n");
        if (column.Last().Type.SpecialType == SpecialType.System_String)
            code.Append("                return item => ").Append(Guard(column)).Append(Access(column)).Append(" != null && ")
                .Append(Normalize(Access(column), ignoreCase, removed, false)).Append(".Contains(value);\n");
        else if (column.Last().Type.SpecialType == SpecialType.System_Boolean || column.Last().Type is INamedTypeSymbol nullable && nullable.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
            code.Append("                if (!bool.TryParse(value, out bool expected)) return item => false;\n                return item => ").Append(Guard(column)).Append(Access(column)).Append(" == expected;\n");
        else if (!SupportsSearch(column.Last().Type))
        {
            code.Append("                return item => ")
                .Append(string.Join(" || ", StringLeaves(column, columns).Select(path => "(" + Guard(path) + Access(path) + " != null && " + Normalize(Access(path), ignoreCase, removed, false) + ".Contains(value))")))
                .Append(";\n");
        }
        else
        {
            var type = (INamedTypeSymbol)column.Last().Type;
            IFieldSymbol[] values = EnumValues(type);
            for (int i = 0; i < values.Length; i++)
            {
                string text = type.TypeKind == TypeKind.Enum ? Quote(values[i].Name) : TypeName(type) + ".@" + values[i].Name + ".Value";
                code.Append("                bool match").Append(i).Append(" = ").Append(Normalize(text, ignoreCase, removed, true)).Append(".Contains(value);\n");
            }
            code.Append("                return item => ").Append(Guard(column)).Append('(');
            if (values.Length == 0) code.Append("false");
            for (int i = 0; i < values.Length; i++)
            {
                if (i != 0) code.Append(" || ");
                code.Append("(match").Append(i).Append(" && ").Append(Access(column)).Append(" == ").Append(TypeName(type)).Append(".@").Append(values[i].Name).Append(')');
            }
            code.Append(");\n");
        }
        code.Append("            }\n");
    }

    private static string Normalize(string expression, bool ignoreCase, string removed, bool constant)
    {
        var code = new StringBuilder(expression);
        if (ignoreCase) code.Append(constant ? ".ToLowerInvariant()" : ".ToLower()");
        foreach (char character in removed.Distinct()) code.Append(".Replace(").Append(Quote(character.ToString())).Append(", \"\")");
        return code.ToString();
    }

    private static void EmitSearch(StringBuilder code, string type)
    {
        code.Append("""
                /// <summary>Matches every whitespace-separated term against any allowed field, with null-safe member access. Unknown fields never broaden the search.</summary>
                public static global::System.Linq.Expressions.Expression<global::System.Func<
            """).Append(type).Append("""
            , bool>> CreateSearchPredicate(string? search, global::System.Collections.Generic.IEnumerable<string>? fields = null)
                {
                    if (string.IsNullOrWhiteSpace(search)) return item => true;
                    string[] selected = global::System.Linq.Enumerable.ToArray(fields ?? SearchableFields);
                    var parameter = global::System.Linq.Expressions.Expression.Parameter(typeof(
            """).Append(type).Append("""
            ), "item");
                    global::System.Linq.Expressions.Expression all = global::System.Linq.Expressions.Expression.Constant(true);
                    foreach (string term in search!.Split((char[]?)null, global::System.StringSplitOptions.RemoveEmptyEntries))
                    {
                        global::System.Linq.Expressions.Expression any = global::System.Linq.Expressions.Expression.Constant(false);
                        foreach (string field in selected)
                        {
                            var predicate = GetFieldPredicate(field, term);
                            if (predicate != null)
                                any = global::System.Linq.Expressions.Expression.OrElse(any, new global::Soenneker.DataTables.Gen.Internal.DataTableParameterReplacer(predicate.Parameters[0], parameter).Visit(predicate.Body));
                        }
                        all = global::System.Linq.Expressions.Expression.AndAlso(all, any);
                    }
                    return global::System.Linq.Expressions.Expression.Lambda<global::System.Func<
            """).Append(type).Append("""
            , bool>>(all, parameter);
                }
                /// <summary>Applies generated search predicates before caller-owned filtering, ordering, and pagination. Query provider translation must support the configured string operations.</summary>
                public static global::System.Linq.IQueryable<
            """).Append(type).Append("> ApplySearch(global::System.Linq.IQueryable<").Append(type).Append("""
            > query, string? search, global::System.Collections.Generic.IEnumerable<string>? fields = null)
                {
                    if (query == null) throw new global::System.ArgumentNullException(nameof(query));
                    return string.IsNullOrWhiteSpace(search) ? query : global::System.Linq.Queryable.Where(query, CreateSearchPredicate(search, fields));
                }
            """);
    }
}
